    def test_real_review_expiry_race_preserves_free_wallet(self):
        with producer() as case:
            original_consume = case.access._consume_review_quota

            def expire_after_consume(*args):
                event = original_consume(*args)
                case.clock[0] += datetime.timedelta(minutes=2)
                return event

            for review_type in ("basic", "advanced"):
                for status in ("ready", "missing_key"):
                    case.clock[0] = datetime.datetime.fromisoformat("2026-10-09T03:30:00+00:00")
                    _, token = case.identity("review", expiry="2026-10-09T03:31:00Z")
                    with patch.object(case.access, "_consume_review_quota", side_effect=expire_after_consume):
                        _, (candidate, _) = case.route("review", review_type, status, token=token, save=False, keyed=False)
                    self.assertEqual(("pro", "free"), (candidate["access"]["plan"], candidate["access"]["wallet"]["plan"]))
                    self.accepts(candidate["access"], status=status)

