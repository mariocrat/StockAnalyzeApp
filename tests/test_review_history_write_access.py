    def test_negative_unsafe_and_nonfinite_numbers_at_every_count(self):
        for base in fixtures():
            for path, original in nodes(base):
                if type(original) is int:
                    for wrong in (-1, 2**53, float("inf"), float("-inf"), float("nan")):
                        value = replace(copy.deepcopy(base), path, wrong)
                        # NaN equality is not an immutability proof; compare a
                        # stable serialization-independent object identity instead.
