def nodes(value, path=()):
    yield path, value
    if type(value) is dict:
        for key, child in value.items():
            yield from nodes(child, path + (key,))


def at(value, path):
    for key in path:
        value = value[key]
    return value


def replace(value, path, replacement):
    if not path:
        return replacement
    at(value, path[:-1])[path[-1]] = replacement
    return value


def balance(value, kind, **changes):
    # Update both independent copies to isolate relation/value mutations.
    for parent in ("wallet", "quota"):
        value[parent][kind].update(changes)
    return value


@contextmanager
def producer():
    # Import the module, not its TestCase class into discovery's namespace.
    from tests import test_review_history_producers as producers

    case = producers.HistoryProducerTest(methodName="runTest")
    try:
        case.setUp()
        yield case
    finally:
        case.doCleanups()


class NewHistoryAccessTest(unittest.TestCase):
    def accepts(self, value, *, review_type=None, status="ready"):
        before = copy.deepcopy(value)
        self.assertIsNone(contract.validate_new_history_access(
            value, review_type=review_type or value["review_type"], status=status))
        self.assertEqual(before, value)

    def rejects(self, value, *, review_type="basic", status="ready"):
        before = copy.deepcopy(value)
        with self.assertRaises(contract.HistoryWriteContractError) as raised:
            contract.validate_new_history_access(value, review_type=review_type, status=status)
        self.assertEqual(before, value)
        self.assertNotIn("synthetic-rejected-secret", str(raised.exception))

